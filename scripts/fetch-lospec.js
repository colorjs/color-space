#!/usr/bin/env node
/**
 * Lospec's palette list – the pixel-art community's palettes of two, three and four colors, each by its maker – fetched
 * once into web/js/lospec.js, the field's suggestions' palettes (a pair, a triplet, a four). Most downloaded first.
 * The data is kept in the repo: the build never reaches the network.
 *
 *   node scripts/fetch-lospec.js   → web/js/lospec.js
 */
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const API = 'https://lospec.com/palette-list/load', out = []
for (const n of [2, 3, 4]) {
	for (let page = 0; ; page++) {
		const r = await fetch(`${API}?colorNumberFilterType=exact&colorNumber=${n}&page=${page}&tag=&sortingType=downloads`)
		if (!r.ok) throw new Error(`fetch-lospec: ${n} colors, page ${page}: HTTP ${r.status}`)
		const { palettes } = await r.json()
		if (!palettes?.length) break
		for (const p of palettes) if (p.colors?.length === n) out.push([`${p.title}${p.user?.name ? ` by ${p.user.name}` : ''}`, p.colors.map(c => '#' + c.toLowerCase()).join(' ')])
		await new Promise(ok => setTimeout(ok, 250))   // a guest's pace
	}
}
const file = fileURLToPath(new URL('../web/js/lospec.js', import.meta.url))
writeFileSync(file, `// Lospec's palette list (lospec.com/palette-list) – palettes of two, three and four colors, each by its maker, most downloaded first: generated by scripts/fetch-lospec.js\nexport default ${JSON.stringify(out)}\n`)
console.log(`lospec.js: ${out.length} palettes – ${[2, 3, 4].map(n => `${out.filter(p => p[1].split(' ').length === n).length} of ${n}`).join(', ')}`)
